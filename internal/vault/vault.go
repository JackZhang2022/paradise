// Package vault 提供加密保险库（Vault）的完整操作能力。
//
// 核心功能：
//   - 加密：将明文目录加密存入保险库，文件名和目录名均使用 HMAC 派生
//   - 解密：将保险库中的加密目录解密还原
//   - 写回：将解密修改后的目录重新加密并清理解密副本
//   - 重加密：使用新密钥重新加密整个保险库（用于修改密码）
//   - 备份：创建保险库的 tar.gz 备份
//   - 恢复：从备份恢复保险库
//
// 状态管理：
//
//	解密操作会记录在状态文件中，用于跟踪已解密的目录并支持写回操作。
//	状态文件使用 AES-256-GCM 加密，存储于应用数据目录。
